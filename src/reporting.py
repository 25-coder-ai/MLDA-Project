"""Markdown export of a TrustReport (for PR comments, CI artifacts and audits)."""
from __future__ import annotations

from datetime import datetime, timezone

from src.models.scoring import TrustReport

_ICON = {"TRUSTED": "🟢", "UNCERTAIN": "🟡", "REJECTED": "🔴"}


def to_markdown(r: TrustReport) -> str:
    s = r.summary
    out = [
        f"# TRUST-CODE report `{r.report_id}`",
        "",
        f"> {s.headline}",
        "",
        f"**Trust index:** {s.trust_index:.1f}/100 · 🟢 {s.trusted} trusted · 🟡 {s.uncertain} uncertain · 🔴 {s.rejected} rejected · {s.hard_gates} hard gate(s)",
        f"  ",
        f"Engine {r.engine} · {datetime.fromtimestamp(r.created_at, timezone.utc):%Y-%m-%d %H:%M UTC} · {r.duration_ms / 1000:.1f}s · sandbox `{r.capabilities.get('sandbox')}` · ledger seal `{(r.ledger.seal_hash or '')[:16]}…` ({'intact' if r.ledger.intact else 'BROKEN'})",
        "",
        "## Failure-mode detection",
        "",
        "| Failure mode | Detected | Where |",
        "|---|---:|---|",
    ]
    for row in r.failure_modes:
        out.append(f"| {row.label} | {row.detected} | {', '.join(row.refs[:6]) or '—'} |")
    if r.claims:
        out += ["", "## Review claims", ""]
        for c in r.claims:
            out.append(f"### {_ICON[c.score.verdict]} {c.claim.claim_id} · {c.state} · {c.score.final:.0f}/100")
            out.append(f"`{c.claim.target_file}:{c.claim.target_line_start}-{c.claim.target_line_end}` ({c.claim.claimed_defect_category}) — {c.claim.claim_text}")
            out.append("")
            out += [f"- {e}" for e in c.explanations]
            if c.verifier and c.verifier.flags:
                out.append(f"- **LLM judge ({c.verifier.verdict}):** " + "; ".join(f.label for f in c.verifier.flags))
            out.append("")
    if r.patches:
        out += ["## AI patches", ""]
        for p in r.patches:
            gates = [g.gate for g in p.score.gates if g.triggered]
            out.append(f"### {_ICON[p.score.verdict]} {p.patch.patch_id} · {p.score.verdict} · {p.score.final:.0f}/100")
            out.append(f"_{p.patch.intended_fix_description or 'no description'}_ — `{p.patch.target_file}`" + (f" — **hard gates:** {', '.join(gates)}" if gates else ""))
            out.append("")
            out += [f"- {e}" for e in p.explanations]
            out.append("")
    if r.verifier_audit:
        m = r.verifier_audit.metrics
        out += ["## LLM-judge independence audit", "", r.verifier_audit.conclusion, "",
                f"- accuracy vs ground truth: {m.accuracy}", f"- same-mistake rate: {m.same_mistake_rate}",
                f"- error correlation φ: {m.error_correlation_phi} → independence index {m.independence_index}",
                f"- polarity-insensitive (bias) rate: {m.polarity_insensitive_rate}", ""]
    out += ["## Requirements (baseline)", "", "| ID | Title | Status |", "|---|---|---|"]
    out += [f"| {q.req_id} | {q.title} | {q.status} |" for q in r.requirements]
    out += ["", "---", "_Generated by TRUST-CODE — every verdict is backed by deterministic evidence; no LLM participates in judging._"]
    return "\n".join(out) + "\n"
